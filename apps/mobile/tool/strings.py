BANNED_ZH = ["还没", "没能", "免得", "搭的", "咋", "啥", "搞定", "折腾"]
BANNED_EN = [r"\bjust\b", r"\bgonna\b", r"\bstuff\b"]

def build():
    keys = [k for k, _, _ in S]
    assert len(keys) == len(set(keys)), "重复的键"
    zh, en = {"@@locale": "zh"}, {"@@locale": "en"}
    for k, z, e in S:
        for w in BANNED_ZH:
            assert w not in z, f"{k}: 中文里有「{w}」"
        for w in BANNED_EN:
            assert not re.search(w, e, re.I), f"{k}: English has {w}"
        pz, pe = re.findall(r"\{(\w+)\}", z), re.findall(r"\{(\w+)\}", e)
        assert sorted(pz) == sorted(pe), f"{k}: 占位符不一致 {pz} {pe}"
        zh[k], en[k] = z, e
        if pz:
            zh["@" + k] = {"placeholders": {p: {"type": "int" if p in INT else "String"} for p in dict.fromkeys(pz)}}
    here = pathlib.Path(__file__).resolve().parent.parent / "lib" / "l10n"
    here.mkdir(parents=True, exist_ok=True)
    (here / "app_zh.arb").write_text(json.dumps(zh, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    (here / "app_en.arb").write_text(json.dumps(en, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"{len(S)} 条文案")

if __name__ == "__main__":
    build()
