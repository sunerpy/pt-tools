// 「测试看图」用的验证码：随机 6 个字符，像 NexusPHP 的签到验证码那样是大写字母和数字，画成带干扰的 PNG。
// 不依赖字体文件：字形是 5×7 的点阵，按 captchaScale 放大，每个字上下错开一点，再加几条干扰线和噪点。

// captchaChars 只留点阵字形里不容易认混的字符：去掉了 0/O/D、1/I/L、5/S、8/B、2/Z、U/V/W、G/6 这几组里的一边或两边。
// 「测试看图」要看的是模型能不能看图，认混字形导致的失败会误导人去换模型。
const captchaChars = "ACEFHKMNPRTXY34679"

const (
	captchaScale  = 5
	captchaMargin = 12
)

func randomCaptchaText() string {
	b := make([]byte, 6)
	for i := range b {
		b[i] = captchaChars[rand.IntN(len(captchaChars))]
	}
	return string(b)
}

// renderCaptcha 把 text 画成 PNG；不认识的字符画成空格。
func renderCaptcha(text string) []byte {
	glyphW, glyphH := 5*captchaScale, 7*captchaScale
	step := glyphW + captchaScale*2
	w := captchaMargin*2 + step*len(text)
	h := captchaMargin*2 + glyphH + captchaScale*2
	img := image.NewGray(image.Rect(0, 0, w, h))
	for i := range img.Pix {
		img.Pix[i] = 235
	}
	ink := color.Gray{Y: 30}
	for i, r := range text {
		rows, ok := captchaGlyphs[r]
		if !ok {
			continue
		}
		x0 := captchaMargin + i*step + rand.IntN(captchaScale)
		y0 := captchaMargin + rand.IntN(captchaScale*2)
		for gy, row := range rows {
			for gx, c := range row {
				if c != '#' {
					continue
				}
				for dy := range captchaScale {
					for dx := range captchaScale {
						img.SetGray(x0+gx*captchaScale+dx, y0+gy*captchaScale+dy, ink)
					}
				}
			}
		}
	}
	// 干扰：几条浅灰的斜线和散点，不盖住字
	for range 4 {
		x, y := rand.IntN(w), rand.IntN(h)
		dx, dy := 1, 1-2*rand.IntN(2)
		for range w {
			if x < 0 || x >= w || y < 0 || y >= h {
				break
			}
			img.SetGray(x, y, color.Gray{Y: 150})
			x += dx
			if rand.IntN(3) == 0 {
				y += dy
			}
		}
	}
	for range w * h / 40 {
		img.SetGray(rand.IntN(w), rand.IntN(h), color.Gray{Y: uint8(120 + rand.IntN(80))})
	}
	var buf bytes.Buffer
	_ = png.Encode(&buf, img)
	return buf.Bytes()
}

