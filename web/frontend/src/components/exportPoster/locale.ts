/** Optional localization; the default returns the original text verbatim for desktop posters. */
export function usePosterWords() {
  const locale = inject(PosterLocale, undefined);
  return (text: string) => (locale?.value.startsWith("en") ? (words[text.trim()] ?? text) : text);
}
